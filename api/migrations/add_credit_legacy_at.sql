-- 【已废弃】老会员资格快照方案 → 改为无状态公式推导
--
-- 原方案把「老会员资格」固化到 chatgpt_users.credit_legacy_at，需要人工点按钮打标。
-- 该方案已移除，原因是快照与额度计算用了两套订单状态口径：
--   打标：status = 8（仅在投）
--   算额度：status IN (8, 9)（在投 + 已结束）
-- 结果：老订单跑完的用户永远打不上标，但订单仍计入额度基数，规则自相矛盾。
--
-- 现行规则（见 service/credit_max_policy.go）：额度完全由订单投入推导，无状态。
--   分界前投入合计 >= 门槛 → max = 固定上限 + 分界后投入 × 杠杆
--   否则                  → max = 分界前投入 × 杠杆
--   分界后投入自身也必须达到门槛才计入，不足门槛视为 0（不按比例折算）。
-- 因为 status IN (8, 9) 都计入「分界前」，订单到期不会让额度回弹，
-- 所以不再需要快照，也不需要固化按钮。
--
-- 库里的 credit_legacy_at 列已无代码引用，保留不影响运行。
